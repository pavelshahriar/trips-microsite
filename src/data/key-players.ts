/** Get key players for a team, case-insensitive. */
export function getKeyPlayers(teamName: string): KeyPlayer[] {
  // Direct lookup
  if (KEY_PLAYERS[teamName]) return KEY_PLAYERS[teamName];
  // Case-insensitive fallback
  const lower = teamName.toLowerCase();
  const match = Object.keys(KEY_PLAYERS).find((k) => k.toLowerCase() === lower);
  return match ? KEY_PLAYERS[match] : [];
}
